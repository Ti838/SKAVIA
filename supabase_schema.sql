-- Instead of a single monolithic file or scattered migrations, the SKAVIA
-- database schema is cleanly organized by functional domain under:
--
--   supabase/schema/
--     01_identity_and_rbac.sql          -- Users, Roles, Addresses, Sessions, KYC
--     02_admin_governance.sql           -- Admin RBAC, Passkeys, Audit Logs, Security
--     03_catalog_and_branches.sql       -- Branches, Categories, Services, Skills
--     04_marketplace_and_operations.sql -- Profiles, Matching, Bookings, Projects
--     05_finance_and_escrow.sql         -- Payments, Invoices, Payouts, Maker-Checker
--     06_engagement_and_sync.sql        -- Chat, Reviews, Disputes, Notifications, Sync
--     07_releases_and_ota.sql           -- App Releases, OTA Telemetry & Storage Bucket
--     08_rls_functions_and_indexes.sql  -- RLS Policies, Triggers & B-Tree Indexes
--
-- Execution Order (in Supabase SQL Editor / psql):
--   Run files 01 through 08 sequentially. All DDL statements are idempotent.
